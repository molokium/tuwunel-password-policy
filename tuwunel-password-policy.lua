-- /etc/nginx/lua/tuwunel-password-policy.lua
-- Enforces a password policy on Matrix account creation for Tuwunel.
--
-- Attach it inside the location that proxies /_matrix:
--
--     access_by_lua_file /etc/nginx/lua/tuwunel-password-policy.lua;
--
-- Requirements: zxcvbn-lite.lua + zxcvbn-data.lua in /etc/nginx/lua, and in
-- the http{} block:
--
--     lua_package_path "/etc/nginx/lua/?.lua;;";
--     init_by_lua_block {
--         require("zxcvbn-lite").init(require("zxcvbn-data"))
--     }
--
-- Policy:
--   * at least MIN_LEN characters
--   * printable ASCII only (no spaces, no Persian/Arabic/Cyrillic, no emoji)
--   * zxcvbn score >= MIN_SCORE, i.e. it resists an offline attack
--     (0 = too guessable ... 4 = strong; 3 is zxcvbn's "safely unguessable")
--
-- Only POST bodies are inspected, and only for the registration URIs (plus
-- /account/password when CHECK_PASSWORD_CHANGES is enabled). Every other
-- request is passed straight through to Tuwunel untouched.

local MIN_LEN                = 14
local MIN_SCORE              = 4      -- raise to 4 for a stricter policy
local REQUIRE_PASSWORD       = true   -- reject account creation with no password
local CHECK_PASSWORD_CHANGES = true  -- also enforce on /_matrix/client/*/account/password

local zxcvbn = require "zxcvbn-lite"

local REGISTER_URIS = {
    ["/_matrix/client/v3/register"] = true,
    ["/_matrix/client/r0/register"] = true,
}

local CHANGE_URIS = {
    ["/_matrix/client/v3/account/password"] = true,
    ["/_matrix/client/r0/account/password"] = true,
}

local MSG_LENGTH  = string.format("Password must be at least %d characters long.", MIN_LEN)
local MSG_CHARSET = "Password may only contain English letters, numbers and symbols (no spaces or non-English characters)."
local MSG_MISSING = "A password is required to create an account."
local MSG_WEAK    = "Password is too easy to guess: %s."
local MSG_WEAK_GENERIC = "Password is too easy to guess. Use a longer password with several unrelated words."

---------------------------------------------------------------------------
-- reasons, derived from the match zxcvbn liked best
---------------------------------------------------------------------------

local REASON = {
    dictionary = "it contains a common word or name",
    spatial    = "it follows a keyboard pattern",
    ["repeat"] = "it repeats the same characters",
    sequence   = "it contains a run of letters or numbers",
    date       = "it looks like a date or a year",
}

-- weight patterns so a keyboard walk is reported as such even when the same
-- substring also happens to sit in the password dictionary
local WEIGHT = { spatial = 1.3, ["repeat"] = 1.3, sequence = 1.25, dictionary = 1.0, date = 0.9 }

local function weakness(analysis)
    local best_pattern, best_score = nil, 0
    for _, m in ipairs(analysis.matches) do
        local len = m.j - m.i + 1
        local weight = WEIGHT[m.pattern]
        if weight and len >= 4 and REASON[m.pattern] then
            local score = len * weight
            if score > best_score then
                best_pattern, best_score = m.pattern, score
            end
        end
    end
    if best_pattern then
        return string.format(MSG_WEAK, REASON[best_pattern])
    end
    return MSG_WEAK_GENERIC
end

---------------------------------------------------------------------------
-- helpers
---------------------------------------------------------------------------

local function cors_headers()
    -- This response is generated by nginx, not proxied from tuwunel, so the
    -- headers tuwunel normally adds are missing. Without them a browser on a
    -- different origin cannot read the error body and the client shows a
    -- generic failure instead of the reason.
    ngx.header["Access-Control-Allow-Origin"] = "*"
    ngx.header["Access-Control-Allow-Methods"] = "GET, HEAD, POST, PUT, DELETE, OPTIONS"
    local req_headers = ngx.req.get_headers()["access-control-request-headers"]
    ngx.header["Access-Control-Allow-Headers"] = req_headers
        or "Authorization, Content-Type, X-Requested-With"
    ngx.header["Access-Control-Expose-Headers"] = "Content-Type"
    ngx.header["Access-Control-Max-Age"] = "86400"
    ngx.header["Vary"] = "Origin"
end

local function reject(message)
    ngx.status = 400
    cors_headers()
    ngx.header["Content-Type"] = "application/json"
    ngx.header["Cache-Control"] = "no-store"
    ngx.print('{"errcode":"M_WEAK_PASSWORD","error":"' .. message .. '"}')
    ngx.log(ngx.WARN, "tuwunel-password-policy: reject ",
            (ngx.var.remote_addr or "-"), " ", (ngx.var.uri or "-"), ": ", message)
    return ngx.exit(400)
end

local function read_body()
    ngx.req.read_body()
    local body = ngx.req.get_body_data()
    if body then
        return body
    end
    -- body larger than client_body_buffer_size: nginx spooled it to a file
    local path = ngx.req.get_body_file()
    if not path then
        return nil
    end
    local fh = io.open(path, "rb")
    if not fh then
        ngx.log(ngx.ERR, "tuwunel-password-policy: cannot open ", path)
        return nil
    end
    body = fh:read("*a")
    fh:close()
    return body
end

local JSON_UNESCAPE = {
    ['"'] = '"', ["\\"] = "\\", ["/"] = "/",
    b = "\b", f = "\f", n = "\n", r = "\r", t = "\t",
}

-- Minimal JSON string reader: used when lua-cjson is not installed.
-- Returns nil when the field is absent or cannot be decoded.
local function json_string_field(body, key)
    local _, stop = body:find('"' .. key .. '"%s*:%s*"')
    if not stop then
        return nil
    end
    local buf, i = {}, stop + 1
    while i <= #body do
        local c = body:sub(i, i)
        if c == '"' then
            return table.concat(buf)
        elseif c == "\\" then
            local n = body:sub(i + 1, i + 1)
            if n == "u" then
                local cp = tonumber(body:sub(i + 2, i + 5), 16)
                if not cp then
                    return nil
                end
                -- non-ASCII escapes become a byte that fails the charset check
                buf[#buf + 1] = (cp > 0x20 and cp < 0x7F) and string.char(cp) or "\255"
                i = i + 6
            elseif JSON_UNESCAPE[n] then
                buf[#buf + 1] = JSON_UNESCAPE[n]
                i = i + 2
            else
                return nil
            end
        else
            buf[#buf + 1] = c
            i = i + 1
        end
    end
    return nil
end

-- Returns a table: { password=..., new_password=..., has_auth=bool }
local function parse_body(body)
    local ok, cjson = pcall(require, "cjson.safe")
    if ok and type(cjson) == "table" then
        local obj = cjson.decode(body)
        if type(obj) == "table" then
            local out = { has_auth = type(obj.auth) == "table" }
            if type(obj.password) == "string" then
                out.password = obj.password
            end
            if type(obj.new_password) == "string" then
                out.new_password = obj.new_password
            end
            -- a few clients repeat the secret inside the UIA auth dict
            if not out.password and out.has_auth and type(obj.auth.password) == "string" then
                out.password = obj.auth.password
            end
            return out
        end
    end
    return {
        has_auth  = body:find('"auth"%s*:') ~= nil,
        password  = json_string_field(body, "password"),
        new_password = json_string_field(body, "new_password"),
    }
end

---------------------------------------------------------------------------
-- the checks
---------------------------------------------------------------------------

local function check_password(pw)
    if #pw < MIN_LEN then
        return false, MSG_LENGTH
    end

    for i = 1, #pw do
        local b = pw:byte(i)
        if b < 0x21 or b > 0x7E then          -- space, control, non-ASCII
            return false, MSG_CHARSET
        end
    end

    if not zxcvbn.ready then
        -- fail closed rather than silently accepting everything
        ngx.log(ngx.ERR, "tuwunel-password-policy: zxcvbn-lite is not initialised. ",
                "Add to the http{} block: init_by_lua_block { require(\"zxcvbn-lite\").init(require(\"zxcvbn-data\")) }")
        return false, "The server's password policy is misconfigured. Please tell the administrator."
    end

    local analysis = zxcvbn.analyze(pw)
    if analysis.score < MIN_SCORE then
        return false, weakness(analysis)
    end

    return true
end

---------------------------------------------------------------------------
-- main
---------------------------------------------------------------------------

if ngx.req.get_method() ~= "POST" then
    return
end

local uri = ngx.var.uri or ""
if uri:sub(-1) == "/" then
    uri = uri:sub(1, -2)
end

local field
if REGISTER_URIS[uri] then
    if ngx.var.arg_kind == "guest" then
        return  -- guest accounts have no password
    end
    field = "password"
elseif CHECK_PASSWORD_CHANGES and CHANGE_URIS[uri] then
    field = "new_password"
else
    return
end

local body = read_body()
if not body or body == "" then
    return  -- empty POST: client is asking which registration flows exist
end

local parsed = parse_body(body)
local password = parsed[field]

if not password then
    -- no secret in the body: only interesting if the request tries to finish
    -- account creation (UIA completion) without one
    if field == "password" and REQUIRE_PASSWORD and parsed.has_auth then
        reject(MSG_MISSING)
    end
    return
end

local ok, message = check_password(password)
if not ok then
    reject(message)
end